function byPath<T extends { path: string }>(a: T, b: T): number {
  return a.path < b.path ? -1 : a.path > b.path ? 1 : 0;
}

function sha256(data: string | Buffer): string {
  return createHash('sha256').update(data).digest('hex');
}

function humanize(name: string): string {
  return name.replace(/_+/g, ' ').trim();
}

/** A file and identifier stem for a Creator component name. */
function stem(name: string): string {
  const clean = name.replace(/[^A-Za-z0-9_]/g, '_');
  return /^[A-Za-z_]/.test(clean) ? clean : `_${clean}`;
}

function pascal(name: string): string {
  const words = name.split(/[^A-Za-z0-9]+/).filter(Boolean);
  const joined = words.map((w) => w[0]!.toUpperCase() + w.slice(1)).join('');
  return /^[A-Za-z]/.test(joined) ? joined : `C${joined}`;
}

function fieldSpec(field: UiField): FieldSpec {
  const drawn = field.status === 'generated' && (DRAWN.has(field.widget) || drawsLookup(field));
  const spec: FieldSpec = {
    name: field.name,
    label: field.label,
    widget: field.widget,
    required: field.required,
    readonly: field.readonly,
    generated: drawn,
  };
  // An empty choice is a list Creator fills from a script at run time; it is not an option.
  const choices = (field.choices ?? []).filter((choice) => choice !== '');
  if (choices.length) spec.choices = choices;
  if (field.maxLength !== undefined) spec.maxLength = field.maxLength;
  if (field.pattern !== undefined) spec.pattern = field.pattern;
  if (field.decimalPlaces !== undefined) spec.decimalPlaces = field.decimalPlaces;
  if (field.currencyCode !== undefined) spec.currencyCode = field.currencyCode;
  if (field.accept !== undefined) spec.accept = field.accept;
  if (field.uploadEndpoint !== undefined) spec.uploadEndpoint = field.uploadEndpoint;
  const lookup = lookupSpec(field);
  if (lookup) spec.lookup = lookup;
  if (field.subfields?.length) spec.subfields = field.subfields.map((sub) => fieldSpec(sub));
  // A credential field type, decided by the model — the draft keeps it out by flag, not by name.
  if (field.matrixId === 'encrypted' || (field.widget as string) === 'password') spec.secret = true;
  if (field.widget === 'section') spec.titled = field.titled !== false;
  if (field.note !== undefined) spec.note = field.note;
  if (!drawn && LOOKUP_WIDGETS.has(field.widget) && field.status === 'generated') spec.todo = field.todo ?? 'the export names no parent form for this lookup';
  else if (!drawn) spec.todo = field.todo ?? `the ${field.widget} control is not generated yet`;
  return spec;
}

function buttonsOf(app: App, formName: string): FormSpec['buttons'] {
  const out: FormSpec['buttons'] = { add: [], edit: [] };
  const form = app.forms.find((f) => f.name === formName);
  for (const action of form?.actions ?? []) {
    const list = /edit/i.test(action.event) && !/add/i.test(action.event) ? out.edit : /add/i.test(action.event) ? out.add : undefined;
    if (!list) continue;
    for (const button of action.buttons) {
      const type: ButtonSpec['type'] = button.type === 'submit' || button.type === 'reset' || button.type === 'cancel' ? button.type : 'button';
      const label = button.displayName ?? humanize(button.name);
      if (!list.some((b) => b.name === button.name)) list.push({ name: button.name, label, type });
    }
  }
  return out;
}

/**
 * The registry key for a handler module: the model names the vanilla hashed
 * asset (`@@asset:slate/assets/handlers/<base>.js@@`); the React app keeps the
 * same generated module under `handlers/<base>` in src/generated/handlers.ts.
 */
function handlerModuleKey(module: string): string {
  const match = /^@@asset:slate\/assets\/handlers\/(.+)\.js@@$/.exec(module);
  return `handlers/${match?.[1] ?? module}`;
}

function handlerSpec(handler: UiHandler): HandlerSpec {
  const spec: HandlerSpec = { event: handler.event, when: handler.when, module: handler.module ? handlerModuleKey(handler.module) : '' };
  if (handler.field) spec.field = handler.field;
  if (handler.recordEvent) spec.recordEvent = handler.recordEvent;
  if (handler.endpoint) spec.endpoint = handler.endpoint;
  if (handler.prefetch) spec.prefetch = handler.prefetch;
  return spec;
}

/** The app spec written to src/generated/model.ts. `flows` comes from machineFlows() over the generated flow modules; generateReactApp passes it. */
export function reactAppSpec(app: App, model: UiModel = generateUi(app).model, flows: FlowSpec[] = []): AppSpec {
  const palette = paletteFor(model.theme?.theme);
  const forms: Record<string, FormSpec> = {};
  for (const form of model.forms) {
    forms[form.name] = {
      name: form.name,
      label: form.label,
      layout: form.layout ?? 'one',
      fields: form.fields.map(fieldSpec),
      submitEndpoint: form.submitEndpoint,
      ...(form.editSubmitEndpoint ? { editSubmitEndpoint: form.editSubmitEndpoint } : {}),
      recordEndpoint: form.recordEndpoint,
      deleteEndpoint: form.deleteEndpoint,
      ...(form.successMessage ? { successMessage: form.successMessage } : {}),
      buttons: buttonsOf(app, form.name),
      ...(form.handlers.length ? { handlers: form.handlers.map(handlerSpec) } : {}),
      ...(form.stageFields ? { stageFields: form.stageFields } : {}),
    };
  }
  const reports: Record<string, ReportSpec> = {};
  for (const report of model.reports) reports[report.name] = reportSpec(app, report, model.forms);
  const nav: NavSection[] = [];
  const hiddenOnly = new Set<string>();
  const visible = new Set<string>();
  const flowNames = new Set<string>();
  model.nav.forEach((section, sectionIndex) => {
    for (const item of section.items) (section.hidden ? hiddenOnly : visible).add(item.name);
    if (section.hidden) return;
    const items: NavItem[] = [];
    section.items.forEach((item, itemIndex) => {
      if (item.kind === 'systemcomponent') {
        const flowItem = approvalNavItem(approvalComponentAt(app, sectionIndex, itemIndex));
        if (flowItem && !flowNames.has(flowItem.name)) {
          flowNames.add(flowItem.name);
          items.push(flowItem);
        }
        return;
      }
      if ((item.kind === 'form' || item.kind === 'report' || item.kind === 'page') && item.href !== '') {
        items.push({ kind: item.kind, name: item.name, label: item.label, href: item.href });
      }
    });
    if (items.length) nav.push({ label: section.name, items });
  });
  // No approval systemcomponent in the menu but the app has machines: the
  // Approvals section still needs a home, mirroring Creator's built-in section.
  if (!flowNames.size && flows.some((flow) => flow.kind === 'approval')) {
    const items = approvalsSection();
    for (const item of items) flowNames.add(item.name);
    nav.push({ label: 'Approvals', items });
  }
  // A name in a hidden section and in no visible one is denied — the vanilla
  // runtime's hiddenTarget rule. Hidden items keep every kind (list, pivot…):
  // the deny list must cover screens the nav filter would have dropped anyway.
  const denied = [...hiddenOnly].filter((name) => !visible.has(name)).sort();
  return {
    name: model.name || app.name || 'App',
    spec: SPEC_VERSION,
    theme: { accent: palette.accent, accentInk: '#ffffff', menu: palette.menu, ...(model.theme?.font ? { font: model.theme.font } : {}) },
    ...(model.dateFormat ? { dateFormat: model.dateFormat } : {}),
    nav,
    ...(denied.length ? { denied } : {}),
    forms,
    reports,
    ...(model.pages.length ? { pages: pageSpecs(app, model) } : {}),
    ...(flows.length ? { workflows: flows } : {}),
  };
}

function q(value: string): string {
  return JSON.stringify(value);
}

function formModule(form: FormSpec, component: string, governed: boolean): string {
  const fields = form.fields.map((field) => `      <Field name=${q(field.name)} />`).join('\n');
  // A form with no fields (a stateless Creator form) imports no Field and passes no children.
  const view = form.handlers?.length ? `<FormView form={form} edit={edit} handlers={formHandlers}` : '<FormView form={form} edit={edit}';
  const formBody = form.fields.length ? `    ${view}>\n${fields}\n    </FormView>` : `    ${view} />`;
  // Governed forms mount the stage bar above the edit screen; it reads the stored stage from the record.
  const body = governed
    ? `    <>\n    {edit ? <FlowStageBar form={form} rowId={edit} /> : null}\n${formBody}\n    </>`
    : formBody;
  const handlerImport = form.handlers?.length ? `import { formHandlers } from '../handlers';\n` : '';
  return `${HEADER}import { ${form.fields.length ? 'Field, ' : ''}${governed ? 'FlowStageBar, ' : ''}FormView, type ScreenProps } from '@c2c/ui';
${handlerImport}import { model } from '../model';

const form = model.forms[${q(form.name)}]!;

/** ${form.label.replace(/\*\//g, '* /')}: ${form.fields.length} fields in Creator order.${governed ? ' A workflow governs the record: the stage bar above the edit screen runs its transitions.' : ''} */
export default function ${component}({ edit }: ScreenProps) {
  return (
${body}
  );
}
`;
}

function reportModule(report: ReportSpec, component: string): string {
  if (report.view === 'chart') {
    return `${HEADER}import { ChartReport } from '@c2c/ui';
import { model } from '../model';

const report = model.reports[${q(report.name)}]!;

/** ${report.label.replace(/\*\//g, '* /')}: a chart over the report rows. */
export default function ${component}() {
  return <ChartReport report={report} />;
}
`;
  }
  const pending = report.view !== 'list';
  const note = pending
    ? `      <p className="todo" data-view-pending=${q(report.view)}>The ${report.view.replace(/[<>&"]/g, '')} view is not generated yet.</p>\n`
    : '';
  return `${HEADER}import { ReportView, type ScreenProps } from '@c2c/ui';
import { model } from '../model';

const report = model.reports[${q(report.name)}]!;

/** ${report.label.replace(/\*\//g, '* /')}: ${report.columns.length} columns. */
export default function ${component}({ row }: ScreenProps) {
  return (
    <>
${note}      <ReportView report={report} row={row} />
    </>
  );
}
`;
}

