/** Every file of the React app for a Creator app, sorted by path. */
export function generateReactApp(app: App, opts: ReactGenerateOptions = {}): ReactFile[] {
  const ui = generateUi(app);
  // A report on the governed form backs the inbox's record list; a list-like
  // view is preferred but any report on the form answers the filtered query.
  const reportFor = (form: string) =>
    (ui.model.reports.find((report) => report.form === form && (LIST_VIEWS.has(report.view) || report.view === 'list')) ?? ui.model.reports.find((report) => report.form === form))?.name;
  const flows = machineFlows(ui.files, reportFor);
  const spec = reactAppSpec(app, ui.model, flows);
  const files: ReactFile[] = [];
  const gen = (path: string, data: string | Buffer) => files.push({ path, data, owner: 'generated' });

  gen('src/generated/model.ts', `${HEADER}import type { AppSpec } from '@c2c/ui';\n\nexport const model: AppSpec = ${JSON.stringify(spec, null, 2)};\n`);
  const used = new Set<string>();
  // Unique ignoring case: two Creator names that differ only in case must not share a file on a case-insensitive disk.
  const unique = (base: string) => {
    let name = base;
    for (let i = 2; used.has(name.toLowerCase()); i++) name = `${base}${i}`;
    used.add(name.toLowerCase());
    return name;
  };
  const routes: { key: string; component: string; module: string }[] = [];
  const governed = new Set(flows.map((flow) => flow.form));
  // Source order: the model's form and report lists, not the spec maps.
  for (const form of ui.model.forms.map((f) => spec.forms[f.name]!)) {
    const component = unique(`${pascal(form.name)}Form`);
    const module = unique(`forms/${stem(form.name)}`);
    gen(`src/generated/${module}.tsx`, formModule(form, component, governed.has(form.name)));
    routes.push({ key: `form/${form.name}`, component, module });
  }
  for (const report of ui.model.reports.map((r) => spec.reports[r.name]!)) {
    const component = unique(`${pascal(report.name)}Report`);
    const module = unique(`reports/${stem(report.name)}`);
    gen(`src/generated/${module}.tsx`, reportModule(report, component));
    routes.push({ key: `report/${report.name}`, component, module });
  }
  for (const page of ui.model.pages) {
    const component = unique(`${pascal(page.name)}Page`);
    const module = unique(`pages/${stem(page.name)}`);
    gen(`src/generated/${module}.tsx`, pageModule(page.name, page.label, component));
    routes.push({ key: `page/${page.name}`, component, module });
  }
  // The Approvals screen serves both inbox views; the nav links to each.
  const approvalNav = spec.nav.some((section) => section.items.some((item) => item.kind === 'flow'));
  if (approvalNav || flows.some((flow) => flow.kind === 'approval')) {
    const component = unique('ApprovalsScreen');
    const module = unique('workflow/approvals');
    gen(`src/generated/${module}.tsx`, inboxModule(component));
    routes.push({ key: 'flow/approvals', component, module });
    routes.push({ key: 'flow/approvals/completed', component, module });
  }
  // Both inbox views share one module; import each module once.
  const imported = new Set<string>();
  const imports = routes.filter((r) => !imported.has(r.module) && (imported.add(r.module), true));
  gen(
    'src/generated/routes.tsx',
    `${HEADER}import type { RouteTable } from '@c2c/ui';\n${imports.map((r) => `import ${r.component} from './${r.module}';`).join('\n')}\n\nexport const routes: RouteTable = {\n${routes.map((r) => `  ${q(r.key)}: ${r.component},`).join('\n')}\n};\n`,
  );
  gen('src/generated/theme.css', themeCss(ui.model));
  gen('index.html', indexHtml(spec));
  gen('public/c2c-config.js', slateConfigSource({ ...(opts.apiBase ? { apiBase: opts.apiBase } : {}), auth: opts.auth !== false, appTimeZone: appTimeZone(app) }));
  gen('public/manifest.webmanifest', webManifest(spec));
  const rgb = iconColorRgb(ui.model.theme?.iconColor);
  gen('public/icons/icon-192.png', solidPng(192, rgb));
  gen('public/icons/icon-512.png', solidPng(512, rgb));

  // Creator client handlers reuse the same generated modules the vanilla
  // target emits (client/handlers/*.mjs), copied verbatim as lazy TS modules
  // behind a registry. The shared client runtime supplies the browser shim.
  const handlerKeys = new Set<string>();
  for (const modelForm of ui.model.forms) for (const handler of spec.forms[modelForm.name]?.handlers ?? []) handlerKeys.add(handler.module);
  const emitted = new Map(ui.files.filter((f) => f.path.startsWith('client/handlers/')).map((f) => [f.path.slice('client/handlers/'.length).replace(/\.mjs$/, ''), String(f.data)]));
  const handlerModules = [...handlerKeys].filter((key) => emitted.has(key.slice('handlers/'.length))).sort();
  for (const key of handlerModules) gen(`src/generated/${key}.ts`, `${HEADER}// @ts-nocheck\n${emitted.get(key.slice('handlers/'.length))!}`);
  if (handlerModules.length) {
    gen('src/generated/client-runtime.js', clientRuntimeSource());
    gen('src/generated/client-runtime.d.ts', `${HEADER}export function browserShim(fetchImpl?: unknown): unknown;\n`);
    gen(
      'src/generated/handlers.ts',
      // The shim runtime stays behind a dynamic import: only the modules a
      // script actually runs (and the shim itself, on first use) are loaded,
      // keeping the boot bundle inside the build contract.
      `${HEADER}import type { FormHandlers } from '@c2c/ui';\n\nconst modules = {\n${handlerModules.map((key) => `  ${q(key)}: () => import('./${key}'),`).join('\n')}\n};\n\nexport const formHandlers: FormHandlers = {\n  modules,\n  createShim: async (fetchImpl) => ({ shim: (await import('./client-runtime.js')).browserShim(fetchImpl) }),\n};\n`,
    );
  }

  files.push(...templateFiles());
  files.push({ path: 'lib/c2c-ui/pwa/sw.template.js', data: serviceWorker(), owner: 'platform' });
  files.push({ path: 'THIRD_PARTY_NOTICES.md', data: THIRD_PARTY, owner: 'platform' });
  files.push({ path: 'README.md', data: APP_README, owner: 'platform' });

  // The hand-edit guard: every generated file's hash, written last.
  const generated = files.filter((f) => f.owner === 'generated').sort(byPath);
  const manifest = { spec: SPEC_VERSION, files: Object.fromEntries(generated.map((f) => [f.path, sha256(f.data)])) };
  gen(GENERATED_MANIFEST, `${JSON.stringify(manifest, null, 2)}\n`);
  return files.sort(byPath);
}

export interface WriteResult {
  written: string[];
  kept: string[];
  removed: string[];
}

export class HandEditedError extends Error {
  constructor(readonly paths: string[]) {
    super(`generated files were edited by hand: ${paths.join(', ')}. Move the change to src/custom/ (or rerun with --force to discard it).`);
  }
}

/**
 * Write the app into `out`. A first generation writes every file. Into an
 * existing app it rewrites the generated files only, removes generated files
 * the app no longer has, writes missing custom and platform files, and keeps
 * every existing custom file. Platform files are replaced only with
 * `upgradePlatform`. A generated file whose bytes no longer match the recorded
 * hash stops the write unless `force`.
 */
export function writeReactApp(out: string, files: readonly ReactFile[], opts: { upgradePlatform?: boolean; force?: boolean } = {}): WriteResult {
  const result: WriteResult = { written: [], kept: [], removed: [] };
  const manifestPath = join(out, GENERATED_MANIFEST);
  const previous: Record<string, string> = existsSync(manifestPath) ? (JSON.parse(readFileSync(manifestPath, 'utf8')) as { files: Record<string, string> }).files : {};
  const edited = Object.entries(previous)
    .filter(([path, hash]) => existsSync(join(out, path)) && sha256(readFileSync(join(out, path))) !== hash)
    .map(([path]) => path)
    .sort();
  if (edited.length && !opts.force) throw new HandEditedError(edited);
  const next = new Set(files.map((f) => f.path));
  for (const path of Object.keys(previous).sort()) {
    if (next.has(path) || !existsSync(join(out, path))) continue;
    rmSync(join(out, path));
    result.removed.push(path);
  }
  for (const file of files) {
    const dest = join(out, file.path);
    const present = existsSync(dest);
    if (present && (file.owner === 'custom' || (file.owner === 'platform' && !opts.upgradePlatform))) {
      result.kept.push(file.path);
      continue;
    }
    mkdirSync(dirname(dest), { recursive: true });
    writeFileSync(dest, file.data);
    result.written.push(file.path);
  }
  return result;
}
