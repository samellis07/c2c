/**
 * The emitted package.json and lockfile root carry engines.node from
 * REACT_BUILD_NODE_RANGE, the same range doctor D-R1 checks; with the
 * template's engine-strict=true, npm refuses any other Node with a clear error.
 */
function withBuildEngines(rel: string, data: Buffer): Buffer {
  if (rel !== 'package.json' && rel !== 'package-lock.json') return data;
  const json = JSON.parse(data.toString('utf8')) as { engines?: Record<string, string>; packages?: Record<string, { engines?: Record<string, string> }> };
  const root = rel === 'package.json' ? json : json.packages?.[''];
  if (!root) return data;
  root.engines = { ...root.engines, node: REACT_BUILD_NODE_RANGE };
  return Buffer.from(`${JSON.stringify(json, null, 2)}\n`);
}

function templateFiles(): ReactFile[] {
  const out: ReactFile[] = [];
  const walk = (dir: string) => {
    for (const name of readdirSync(dir).sort()) {
      if (name === 'node_modules' || name === 'dist') continue;
      const path = join(dir, name);
      if (statSync(path).isDirectory()) walk(path);
      else {
        const rel = relative(TEMPLATE_DIR, path).split(sep).join('/');
        out.push({ path: rel, data: withBuildEngines(rel, readFileSync(path)), owner: rel.startsWith('src/custom/') ? 'custom' : 'platform' });
      }
    }
  };
  walk(TEMPLATE_DIR);
  return out;
}

