/**
 * React UI target: a Vite + React + TypeScript app for Catalyst Slate, from a
 * Creator app. See docs/react-target.md.
 *
 * The output tree has three owners:
 * - generated: src/generated/**, index.html and the generated public/ files.
 *   Rewritten on every regeneration; c2c-generated.json records their hashes
 *   so a hand edit is detected instead of overwritten.
 * - platform: the build setup and the @c2c/ui library (lib/c2c-ui/**), copied
 *   from packages/ui-react/template. Written on the first generation, then
 *   only by an explicit platform upgrade.
 * - custom: src/custom/**. Written once, when missing; never overwritten.
 *
 * Pure and deterministic: the same app gives the same bytes. No clock, no
 * network, sorted file lists.
 */
