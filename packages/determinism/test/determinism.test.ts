test('node and typescript pins match the running toolchain', () => {
  const pin = toolchain();
  const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8')) as {
    engines: { node: string };
    devDependencies: { typescript: string };
  };
  assert.ok(
    nodeSatisfies(process.versions.node, compat.node.range),
    `Node ${process.versions.node} is outside the supported range ${compat.node.range}`,
  );
  assert.equal(pkg.engines.node, compat.node.range);
  assert.ok(nodeSatisfies(pin.node, pkg.engines.node), `the .nvmrc pin ${pin.node} must satisfy engines.node ${pkg.engines.node}`);
  assert.equal(pkg.devDependencies.typescript, pin.typescript);
  assert.equal(readFileSync(join(root, '.nvmrc'), 'utf8').trim(), pin.node);
  assert.equal(toolchainHeader(), `c2c generated output\nnode: ${pin.node}\ntypescript: ${pin.typescript}\n`);
});

