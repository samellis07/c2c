test('lint flags clocks and unsorted iteration and honors allow comments', () => {
  const src = [
    'const a = Date.now();',
    'const b = new Date();',
    'const c = new Date(0);',
    'const d = Object.keys(obj).length;',
    'const e = Object.entries(obj).sort((x, y) => x[0] < y[0] ? -1 : 1);',
    'const f = Object.keys(obj);',
    'const map = new Map();',
    'for (const x of map.values()) use(x);',
    'const g = [...new Set(items)];',
    'const h = Date.now(); // determinism-allow: runtime clock injected by the caller',
    'const gap = 1;',
    'const i = Date.now(); // determinism-allow:',
    'const s = `kept Date.now() text`;',
    'const t = `${Date.now()}`;',
    'const precache = [...hashed.values()].map((file) => file).sort();',
    'Math.random();',
    'crypto.randomUUID();',
    'performance.now();',
    'process.hrtime();',
    'left.localeCompare(right);',
    'left.localeCompare(right); // determinism-allow: display order that never reaches generated bytes',
    'const gap2 = 1;',
    'left.localeCompare(right); // determinism-allow:',
    'const kept = "localeCompare()";',
  ].join('\n');
  const findings = scanSource('fixture.ts', src);
  const lines = new Set(findings.map((f) => f.line));
  assert.equal(lines.has(1), true, 'Date.now');
  assert.equal(lines.has(2), true, 'new Date()');
  assert.equal(lines.has(3), false, 'new Date(0)');
  assert.equal(lines.has(4), false, 'length only');
  assert.equal(lines.has(5), false, 'sorted entries');
  assert.equal(lines.has(6), true, 'unsorted keys');
  assert.equal(lines.has(8), true, 'map values');
  assert.equal(lines.has(9), true, 'set spread');
  assert.equal(lines.has(10), false, 'allowed');
  assert.equal(lines.has(12), true, 'empty allow');
  assert.equal(lines.has(13), false, 'string text');
  assert.equal(lines.has(14), true, 'template interpolation');
  assert.equal(lines.has(15), false, 'spread then sort');
  for (const line of [16, 17, 18, 19]) assert.equal(lines.has(line), true, `line ${line}`);
  assert.equal(lines.has(20), true, 'localeCompare');
  assert.equal(lines.has(21), false, 'allowed localeCompare');
  assert.equal(lines.has(22), false, 'gap');
  assert.equal(lines.has(23), true, 'empty locale allow');
  assert.equal(lines.has(24), false, 'localeCompare inside a string');
  assert.equal(findings.some((f) => f.line === 20 && f.kind === 'locale'), true);
});

test('a file-level iteration allow does not cover localeCompare', () => {
  const findings = scanSource('fixture.ts', '/* determinism-allow-file: source order only */\nleft.localeCompare(right);\n');
  assert.equal(findings.some((f) => f.kind === 'locale' && f.line === 2), true);
});

test('the loaded model replays the edits log beside the export', () => {
  const dir = mkdtempSync(join(tmpdir(), 'c2c-tree-'));
  try {
    const ds = join(dir, 'library_application.ds');
    copyFileSync(join(root, 'fixtures/redistributable/library-application-system/library_application.ds'), ds);
    writeFileSync(
      join(dir, 'library_application.edits.json'),
      `${JSON.stringify({ version: 1, edits: [{ op: 'addField', form: 'Book', field: 'Shelf', type: 'text' }] }, null, 2)}\n`,
    );
    const fields = loadApp(ds).forms.find((f) => f.name === 'Book')!.fields.map((f) => f.name);
    assert.ok(fields.includes('Shelf'), 'the edits log is replayed into the generated tree\'s model');
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
});

test('gallery script is not part of the default test run and refuses a missing directory', () => {
  const env = { ...process.env };
  delete env.C2C_GALLERY_DIR;
  const child = spawnSync(process.execPath, [join(root, 'dist/determinism/src/gallery.js')], {
    encoding: 'utf8',
    cwd: root,
    env,
  });
  assert.equal(child.status, 2);
  assert.match(child.stderr, /C2C_GALLERY_DIR/);
});

function runOnce(target: string): Manifest {
  const child = spawnSync(process.execPath, [join(root, 'dist/determinism/src/gallery.js'), '--once', target], {
    encoding: 'utf8',
    cwd: root,
    maxBuffer: 64 * 1024 * 1024,
  });
  assert.equal(child.status, 0, child.stderr || child.stdout);
  return JSON.parse(child.stdout) as Manifest;
}

for (const name of FIXTURES) {
  test(`${name} generates byte-identical trees in-process, across processes, and against the snapshot`, () => {
    const target = join(root, 'fixtures/redistributable', name);
    const first = manifestFor(target);
    const second = manifestFor(target);
    assert.deepEqual(second, first, diffManifest(first, second).join('\n'));
    const left = runOnce(target);
    const right = runOnce(target);
    assert.deepEqual(left, first, diffManifest(first, left).slice(0, 30).join('\n'));
    assert.deepEqual(right, left, diffManifest(left, right).slice(0, 30).join('\n'));
    assert.equal(digestOf(left), digestOf(first));
    assert.ok(first.files.some((file) => file.path === 'c2c-build.txt'));
    assert.ok(first.files.some((file) => file.path === 'iac/project-template-1.0.0.json'));
    const snap = parseManifestFiles(readFileSync(manifestPath(join(root, MANIFESTS_DIR), name), 'utf8'));
    assert.deepEqual(
      first.files,
      snap,
      diffManifest({ node: first.node, typescript: first.typescript, files: snap }, first).slice(0, 40).join('\n'),
    );
  });
}

test('committed manifests are canonical, track the fixture set, and match the update tool', () => {
  const manifestsDir = join(root, MANIFESTS_DIR);
  assert.deepEqual(manifestNames(manifestsDir), FIXTURES);
  for (const name of FIXTURES) {
    const text = readFileSync(manifestPath(manifestsDir, name), 'utf8');
    assert.equal(renderManifest({ node: '', typescript: '', files: parseManifestFiles(text) }), text, `${name} is not canonical`);
  }
  const dir = mkdtempSync(join(tmpdir(), 'c2c-manifests-'));
  try {
    const { written, removed } = updateManifests(join(root, FIXTURES_DIR), dir);
    assert.deepEqual(removed, []);
    assert.deepEqual(written, FIXTURES);
    for (const name of FIXTURES) {
      assert.equal(readFileSync(join(dir, `${name}.sha256`), 'utf8'), readFileSync(manifestPath(manifestsDir, name), 'utf8'));
    }
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
});

test('a stale or drifting committed manifest is reported by name', () => {
  const manifestsDir = join(root, MANIFESTS_DIR);
  const dir = mkdtempSync(join(tmpdir(), 'c2c-manifests-'));
  try {
    copyManifests(manifestsDir, dir);
    const path = join(dir, 'freight-forwarding.sha256');
    const text = readFileSync(path, 'utf8');
    writeFileSync(path, text.replace(/^([0-9a-f]{64})  (c2c-mail\.json)$/m, `${'f'.repeat(64)}  $2`));
    const problems = checkManifests(join(root, FIXTURES_DIR), dir);
    assert.equal(problems.length, 1);
    assert.match(problems[0]!, /freight-forwarding: committed manifest is stale/);
    assert.match(problems[0]!, /changed c2c-mail\.json/);
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
});

