test('lint flags clocks and unsorted iteration and honors allow comments', () => {
  const src = [
    'const a = Date.now();',
    'const b = new Date();',
    'const c = new Date(0);',
    'const d = Object.keys(obj).length;',
    'const e = Object.entries(obj).sort((x, y) => x[0] < y[0] ? -1 : 1);',
    'const f = Object.keys(obj);',
    'const map = new Map();',
    'for (const x of map.values()) use(x);',
    'const g = [...new Set(items)];',
    'const h = Date.now(); // determinism-allow: runtime clock injected by the caller',
    'const gap = 1;',
    'const i = Date.now(); // determinism-allow:',
    'const s = `kept Date.now() text`;',
    'const t = `${Date.now()}`;',
    'const precache = [...hashed.values()].map((file) => file).sort();',
    'Math.random();',
    'crypto.randomUUID();',
    'performance.now();',
    'process.hrtime();',
    'left.localeCompare(right);',
    'left.localeCompare(right); // determinism-allow: display order that never reaches generated bytes',
    'const gap2 = 1;',
    'left.localeCompare(right); // determinism-allow:',
    'const kept = "localeCompare()";',
  ].join('\n');
  const findings = scanSource('fixture.ts', src);
  const lines = new Set(findings.map((f) => f.line));
  assert.equal(lines.has(1), true, 'Date.now');
  assert.equal(lines.has(2), true, 'new Date()');
  assert.equal(lines.has(3), false, 'new Date(0)');
  assert.equal(lines.has(4), false, 'length only');
  assert.equal(lines.has(5), false, 'sorted entries');
  assert.equal(lines.has(6), true, 'unsorted keys');
  assert.equal(lines.has(8), true, 'map values');
  assert.equal(lines.has(9), true, 'set spread');
  assert.equal(lines.has(10), false, 'allowed');
  assert.equal(lines.has(12), true, 'empty allow');
  assert.equal(lines.has(13), false, 'string text');
  assert.equal(lines.has(14), true, 'template interpolation');
  assert.equal(lines.has(15), false, 'spread then sort');
  for (const line of [16, 17, 18, 19]) assert.equal(lines.has(line), true, `line ${line}`);
  assert.equal(lines.has(20), true, 'localeCompare');
  assert.equal(lines.has(21), false, 'allowed localeCompare');
  assert.equal(lines.has(22), false, 'gap');
  assert.equal(lines.has(23), true, 'empty locale allow');
  assert.equal(lines.has(24), false, 'localeCompare inside a string');
  assert.equal(findings.some((f) => f.line === 20 && f.kind === 'locale'), true);
});

test('a file-level iteration allow does not cover localeCompare', () => {
  const findings = scanSource('fixture.ts', '/* determinism-allow-file: source order only */\nleft.localeCompare(right);\n');
  assert.equal(findings.some((f) => f.kind === 'locale' && f.line === 2), true);
});

test('Creator import and live-table diff order do not depend on LANG', () => {
  const script = `
    import { deriveIr, parse } from './dist/core/src/index.js';
    import { generateCreatorImport } from './dist/data/src/index.js';
    import { applyTablePlan } from './dist/deploy/src/tables.js';
    const source = ['application "LocaleOrder"', '{', ...['Ångström', 'Aardvark', 'Æther', 'Zulu'].flatMap((name) => ['form ' + name, '{', 'Name', '(', 'type = text', ')', '}']), '}', ''].join('\\n');
    const app = deriveIr(parse(source));
    const imported = generateCreatorImport(app).order;
    const names = ['Zulu', 'Æther', 'Ångström', 'Aardvark'];
    const diff = await applyTablePlan('1001', [], async () => ({ status: 200, body: { data: names.map((table_name, i) => ({ table_name, table_id: String(i + 1), columns: [] })) } }));
    process.stdout.write(JSON.stringify({ imported, live: diff.tables?.map((table) => table.table_name) }));
  `;
  const output = (lang: string) => {
    const env = { ...process.env, LANG: lang, LC_ALL: lang };
    const child = spawnSync(process.execPath, ['--input-type=module', '-e', script], {
      cwd: root,
      env,
      encoding: 'utf8',
    });
    assert.equal(child.status, 0, child.stderr || child.stdout);
    return child.stdout;
  };
  assert.equal(output('da_DK.UTF-8'), output('C'));
});

