import assert from 'node:assert/strict';
import { execFileSync, spawnSync } from 'node:child_process';
import { chmodSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import test from 'node:test';

const ROOT = resolve(fileURLToPath(new URL('.', import.meta.url)), '../..');
const SCRIPT = join(ROOT, 'scripts/det-rebase-regen.mjs');

/** git with an isolated HOME so the fixture never sees ambient git config. */
function git(dir, args) {
  const home = mkdtempSync(join(tmpdir(), 'c2c-det-regen-home-'));
  try {
    const env = Object.fromEntries(
      Object.entries(process.env).filter(([key]) => !key.startsWith('GIT_')),
    );
    env.HOME = home;
    env.GIT_CONFIG_NOSYSTEM = '1';
    env.GIT_CONFIG_GLOBAL = join(home, '.gitconfig');
    writeFileSync(env.GIT_CONFIG_GLOBAL, '');
    return execFileSync('git', ['-c', 'user.name=t', '-c', 'user.email=t@example.test', ...args], {
      cwd: dir,
      encoding: 'utf8',
      env,
    });
  } finally {
    rmSync(home, { recursive: true, force: true });
  }
}

function write(dir, path, contents) {
  const file = join(dir, path);
  mkdirSync(join(file, '..'), { recursive: true });
  writeFileSync(file, contents);
}

function commitAll(dir, message) {
  git(dir, ['add', '-A']);
  git(dir, ['commit', '-m', message]);
}

/** A stub `npm` that records each run and regenerates the status doc. */
function stubNpm(dir) {
  const bin = join(dir, 'stub-bin');
  mkdirSync(bin, { recursive: true });
  const npm = join(bin, 'npm');
  writeFileSync(
    npm,
    '#!/bin/sh\necho "regenerated by stub npm: $*" >> docs/determinism-status.md\n',
  );
  chmodSync(npm, 0o755);
  return bin;
}

function runScript(repo, stubBin, extraArgs = []) {
  const env = Object.fromEntries(
    Object.entries(process.env).filter(([key]) => !key.startsWith('GIT_')),
  );
  delete env.C2C_FIXTURES_DIR;
  delete env.C2C_GALLERY_DIR;
  env.PATH = `${stubBin}:${env.PATH}`;
  return spawnSync(process.execPath, [SCRIPT, ...extraArgs], {
    cwd: repo,
    encoding: 'utf8',
    env,
  });
}

/** Remote + clone fixture: base commit pushed, then origin/main advanced by a peer. */
function fixture(dir, { advance }) {
  const remote = join(dir, 'remote.git');
  git(dir, ['init', '--bare', remote]);
  const repo = join(dir, 'repo');
  git(dir, ['init', '-b', 'main', repo]);
  git(repo, ['remote', 'add', 'origin', remote]);
  write(repo, 'code/app.txt', 'base\n');
  write(repo, 'packages/determinism/test/manifests/app.sha256', `${'a'.repeat(64)}  p\n`);
  write(repo, 'docs/determinism-status.md', '# status\n');
  write(repo, 'tests/ratchet/todo-kinds.json', '{}\n');
  commitAll(repo, 'base');
  git(repo, ['push', 'origin', 'main']);

  const peer = join(dir, 'peer');
  git(dir, ['clone', remote, peer]);
  git(peer, ['checkout', 'main']);
  advance(peer);
  git(peer, ['push', 'origin', 'main']);
  git(repo, ['fetch', 'origin']);
  return repo;
}

test('code commits replay, old regens drop, one fresh regen lands last', () => {
  const dir = mkdtempSync(join(tmpdir(), 'c2c-det-regen-'));
  try {
    const repo = fixture(dir, {
      advance(peer) {
        write(peer, 'code/main-side.txt', 'main moved\n');
        write(peer, 'packages/determinism/test/manifests/app.sha256', `${'b'.repeat(64)}  p\n`);
        commitAll(peer, 'main: code plus its own regen');
      },
    });
    const stubBin = stubNpm(dir);

    write(repo, 'code/one.txt', 'one\n');
    commitAll(repo, 'code one');
    write(repo, 'packages/determinism/test/manifests/app.sha256', `${'c'.repeat(64)}  p\n`);
    commitAll(repo, 'Regenerate determinism manifests');
    write(repo, 'code/two.txt', 'two\n');
    commitAll(repo, 'code two');
    write(repo, 'docs/determinism-status.md', '# stale branch status\n');
    write(repo, 'tests/ratchet/todo-kinds.json', '{"stale":1}\n');
    commitAll(repo, 'Regenerate determinism manifests, status and TODO ratchet');

    const result = runScript(repo, stubBin);
    assert.equal(result.status, 0, result.stderr);

    const subjects = git(repo, ['log', '--reverse', '--format=%s', 'origin/main..HEAD']).trim().split('\n');
    assert.deepEqual(subjects, ['code one', 'code two', 'Regenerate determinism manifests']);
    assert.equal(readFileSync(join(repo, 'code/one.txt'), 'utf8'), 'one\n');
    assert.equal(readFileSync(join(repo, 'code/two.txt'), 'utf8'), 'two\n');
    assert.equal(
      readFileSync(join(repo, 'code/main-side.txt'), 'utf8'),
      'main moved\n',
      'origin/main commits are the new base',
    );
    assert.match(
      readFileSync(join(repo, 'docs/determinism-status.md'), 'utf8'),
      /regenerated by stub npm/,
    );
    const head = git(repo, ['rev-parse', 'HEAD']).trim();
    const line = result.stdout.trim().split('\n').at(-1);
    assert.match(line, /^det:rebase-regen: base=[0-9a-f]{12} dropped=2 regen=[0-9a-f]{12}$/);
    assert.ok(line.endsWith(`regen=${head.slice(0, 12)}`), `summary names HEAD: ${line}`);
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
});

test('a non-generated conflict stops non-zero and leaves the repo clean', () => {
  const dir = mkdtempSync(join(tmpdir(), 'c2c-det-regen-conflict-'));
  try {
    const repo = fixture(dir, {
      advance(peer) {
        write(peer, 'code/app.txt', 'main side\n');
        commitAll(peer, 'main edits app');
      },
    });
    const stubBin = stubNpm(dir);

    write(repo, 'packages/determinism/test/manifests/app.sha256', `${'d'.repeat(64)}  p\n`);
    commitAll(repo, 'Regenerate determinism manifests');
    write(repo, 'code/app.txt', 'branch side\n');
    commitAll(repo, 'branch edits app');
    const before = git(repo, ['rev-parse', 'HEAD']).trim();

    const result = runScript(repo, stubBin);
    assert.notEqual(result.status, 0, 'conflict must fail');
    assert.match(result.stderr, /non-generated conflict/);
    assert.equal(git(repo, ['rev-parse', 'HEAD']).trim(), before, 'HEAD restored');
    assert.equal(git(repo, ['status', '--porcelain']).trim(), '', 'worktree clean');
    assert.throws(() => git(repo, ['rev-parse', '--verify', 'CHERRY_PICK_HEAD']));
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
});
