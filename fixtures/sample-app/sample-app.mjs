export function sampleWorkflow() {
  return [
    '\tworkflow',
    '\t{',
    '\t\tform',
    '\t\t{',
    '\t\t\tSample_Validation as "Sample Validation"',
    '\t\t\t{',
    '\t\t\t\ttype = form',
    '\t\t\t\tform = Sample_Item',
    '\t\t\t\trecord event = on add or edit',
    '\t\t\t\ton validate',
    '\t\t\t\t{',
    '\t\t\t\t\tactions',
    '\t\t\t\t\t{',
    '\t\t\t\t\t\tcustom deluge script',
    '\t\t\t\t\t\t(',
    '\t\t\t\t\t\t\tif(input.Quantity != null && input.Quantity <= 0)',
    '\t\t\t\t\t\t\t{',
    '\t\t\t\t\t\t\t\talert "Quantity must be greater than zero";',
    '\t\t\t\t\t\t\t\tcancel submit;',
    '\t\t\t\t\t\t\t}',
    '\t\t\t\t\t\t\tif(input.Unit_Price != null && input.Unit_Price < 0)',
    '\t\t\t\t\t\t\t{',
    '\t\t\t\t\t\t\t\talert "Unit price cannot be negative";',
    '\t\t\t\t\t\t\t\tcancel submit;',
    '\t\t\t\t\t\t\t}',
    '\t\t\t\t\t\t\tif(input.Quantity != null && input.Unit_Price != null)',
    '\t\t\t\t\t\t\t{',
    '\t\t\t\t\t\t\t\tinput.Total_Amount = input.Quantity * input.Unit_Price;',
    '\t\t\t\t\t\t\t}',
    '\t\t\t\t\t\t\tif(input.Status == null || input.Status == "" || input.Status == "Draft")',
    '\t\t\t\t\t\t\t{',
    '\t\t\t\t\t\t\t\tinput.Status = "Submitted";',
    '\t\t\t\t\t\t\t}',
    '\t\t\t\t\t\t)',
    '\t\t\t\t\t}',
    '\t\t\t\t}',
    '\t\t\t}',
    '\t\t}',
    '\t}',
  ];
}

